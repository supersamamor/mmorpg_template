using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using Game.Content.Loading;
using Game.Content.Themes;
using Game.Content.Validation;

namespace Game.ThemeImport;

/// <summary>What one import run is given.</summary>
/// <param name="MappingPath">The mapping file.</param>
/// <param name="ThemesDir">The folder that holds the theme folders (the new theme is written there, next to <c>default</c>).</param>
/// <param name="ContentDir">The content folder (to know which keys content uses, and for the checks).</param>
/// <param name="PackDir">The pack folder; null means the mapping's <c>pack</c>.</param>
/// <param name="Check">Write nothing; only say what would change.</param>
public sealed record ImportOptions(string MappingPath, string ThemesDir, string ContentDir, string? PackDir = null, bool Check = false);

/// <summary>One file the run wrote or would write.</summary>
/// <param name="Key">The asset key.</param>
/// <param name="Path">The file, relative to the theme folder.</param>
/// <param name="Changed">True when its bytes differ from what was on disk.</param>
/// <param name="Notes">The fixes made, for the report.</param>
public sealed record ImportedFile(string Key, string Path, bool Changed, IReadOnlyList<string> Notes);

/// <summary>The result of a run: files, keys left to <c>default</c>, the check's findings, and the report text.</summary>
public sealed class ImportResult
{
    /// <summary>The theme written.</summary>
    public string Theme { get; init; } = "";

    /// <summary>Every file, in key order (the manifest last).</summary>
    public IReadOnlyList<ImportedFile> Files { get; init; } = Array.Empty<ImportedFile>();

    /// <summary>Variants written (keys).</summary>
    public IReadOnlyList<string> Variants { get; init; } = Array.Empty<string>();

    /// <summary>Asset keys content uses that the theme does not list: <c>default</c>'s placeholders stand in.</summary>
    public IReadOnlyList<string> Missing { get; init; } = Array.Empty<string>();

    /// <summary>Mapped keys content does not use (kept for variants, later content, or a typo).</summary>
    public IReadOnlyList<string> Unused { get; init; } = Array.Empty<string>();

    /// <summary>Files in the theme's folders that the mapping does not produce.</summary>
    public IReadOnlyList<string> Stale { get; init; } = Array.Empty<string>();

    /// <summary>The theme contract's findings (ThemeCheck and the content boot) for this theme.</summary>
    public IReadOnlyList<ValidationIssue> Issues { get; init; } = Array.Empty<ValidationIssue>();

    /// <summary>True when any file changed (or, with <c>--check</c>, would change).</summary>
    public bool Changed => Files.Any(f => f.Changed);

    /// <summary>True when the check found an error.</summary>
    public bool Failed => Issues.Any(i => i.Severity == ValidationSeverity.Error);

    /// <summary>The printed report.</summary>
    public string Report { get; init; } = "";
}

/// <summary>
/// The theme import (T-224, docs/THEMES.md): reads a mapping, writes <c>themes/&lt;theme&gt;/</c> (files and <c>asset-manifest.json</c>), runs the theme checks and
/// reports. Idempotent: the output depends only on the mapping and the pack, and a file is written only when its bytes change, so a second run changes nothing.
/// </summary>
public static class Importer
{
    /// <summary>Themes the tool never writes: they are generated by <c>tools/themegen</c>.</summary>
    public static readonly IReadOnlySet<string> Reserved = new HashSet<string>(StringComparer.Ordinal) { "default", "test" };

    /// <summary>The folders the tool writes into, by key prefix.</summary>
    private static readonly (string Prefix, string Folder)[] Folders =
    {
        ("model.", "models"), ("anim.", "anims"), ("icon.", "icons"), ("portrait.", "portraits"), ("sfx.", "audio"), ("music.", "audio"), ("ambience.", "audio"),
        ("vfx.", "vfx"), ("tex.", "textures"), ("sprite.", "sprites"), ("ui.", "ui"), ("font.", "fonts"), ("mat.", "materials"), ("scene.", "scenes"),
    };

    /// <summary>Runs an import. Throws <see cref="MappingException"/> for a mapping that cannot be used.</summary>
    public static ImportResult Run(ImportOptions options)
    {
        var mapping = Mapping.Load(options.MappingPath);
        var theme = mapping.Theme.Trim();
        if (Reserved.Contains(theme) || theme.IndexOfAny(new[] { '/', '\\', '.' }) >= 0)
            throw new MappingException($"{options.MappingPath}: theme '{theme}' cannot be written: {(Reserved.Contains(theme) ? "it is generated by tools/themegen" : "a theme is one plain folder name")}");
        var pack = options.PackDir ?? (mapping.Pack is { } p ? Path.Combine(Path.GetDirectoryName(Path.GetFullPath(options.MappingPath))!, p) : null)
            ?? throw new MappingException($"{options.MappingPath}: no pack folder: set 'pack' in the mapping or pass --pack");
        if (!Directory.Exists(pack)) throw new MappingException($"pack folder {pack} does not exist");
        var themeDir = Path.Combine(options.ThemesDir, theme);

        var files = new List<ImportedFile>();
        var outputs = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
        var manifest = new JsonObject();
        var variants = new List<string>();
        foreach (var (key, asset) in mapping.Assets.OrderBy(a => a.Key, StringComparer.Ordinal))
        {
            var where = $"{options.MappingPath}: {key}";
            var entry = new JsonObject();
            if (asset.Variant is { } variant)
            {
                if (asset.Source is not null) throw new MappingException($"{where}: has both 'source' and 'variant'; a variant draws its base's model");
                if (string.IsNullOrWhiteSpace(variant.Of)) throw new MappingException($"{where}: 'variant.of' names no base key");
                entry["variant_of"] = variant.Of;
                if (variant.Tint is not null) entry["tint"] = variant.Tint;
                if (variant.Scale is { } vs) entry["scale"] = vs;
                if (variant.Outline is { } outline) entry["outline"] = outline.Trim().Equals("false", StringComparison.OrdinalIgnoreCase) ? false : outline;
                AddExtra(entry, asset);
                manifest[key] = entry;
                variants.Add(key);
                continue;
            }
            if (asset.Source is null) throw new MappingException($"{where}: names no 'source' (or 'variant')");
            var source = Path.Combine(pack, asset.Source.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(source)) throw new MappingException($"{where}: source '{asset.Source}' is not in the pack folder {pack}");
            var folder = Folders.FirstOrDefault(f => key.StartsWith(f.Prefix, StringComparison.Ordinal)).Folder
                ?? throw new MappingException($"{where}: '{key}' has no known asset key prefix (VOCABULARY \"Asset key prefixes\")");
            var rest = key[(key.IndexOf('.') + 1)..].Replace('.', '/');
            var isGltf = asset.Source.EndsWith(".glb", StringComparison.OrdinalIgnoreCase) || asset.Source.EndsWith(".gltf", StringComparison.OrdinalIgnoreCase);
            var notes = new List<string>();
            string relative;
            byte[] bytes;
            if (key.StartsWith("model.", StringComparison.Ordinal) || key.StartsWith("anim.", StringComparison.Ordinal))
            {
                if (!isGltf) throw new MappingException($"{where}: '{asset.Source}' is not glTF; export it from Blender as .glb (FBX and OBJ are not read)");
                relative = $"{folder}/{rest}.glb";
                bytes = Model(key, asset, source, mapping, notes, where);
            }
            else
            {
                relative = $"{folder}/{rest}{Path.GetExtension(asset.Source).ToLowerInvariant()}";
                bytes = File.ReadAllBytes(source);
            }
            entry["file"] = relative;
            if (asset.Rig is not null) entry["rig"] = asset.Rig;
            if (asset.Anims is not null) entry["anims"] = asset.Anims;
            if (asset.Attach is not null) entry["attach"] = asset.Attach;
            if (asset.Skinned is not null) entry["skinned"] = asset.Skinned;
            if (asset.ImpactDelay is { } delay) entry["impact_delay"] = delay;
            if (asset.Clips is { Count: > 0 } clips)
            {
                var map = new JsonObject();
                foreach (var (id, name) in clips.OrderBy(c => c.Key, StringComparer.Ordinal)) map[id] = name;
                entry["clips"] = map;
                notes.Add($"{clips.Count} clip(s) mapped");
            }
            AddExtra(entry, asset);
            manifest[key] = entry;
            if (outputs.ContainsKey(relative)) throw new MappingException($"{where}: writes {relative}, which another key writes too");
            outputs[relative] = bytes;
            files.Add(new ImportedFile(key, relative, Differs(Path.Combine(themeDir, relative), bytes), notes));
        }
        if (mapping.Fallbacks is { Count: > 0 } fallbacks)
        {
            var table = new JsonObject();
            foreach (var (name, key) in fallbacks.OrderBy(f => f.Key, StringComparer.Ordinal)) table[name] = key;
            manifest["fallbacks"] = table;
        }
        var manifestBytes = Encoding.UTF8.GetBytes(manifest.ToJsonString(GltfFile.Indented) + "\n");
        files.Add(new ImportedFile("(manifest)", "asset-manifest.json", Differs(Path.Combine(themeDir, "asset-manifest.json"), manifestBytes), Array.Empty<string>()));
        outputs["asset-manifest.json"] = manifestBytes;

        var stale = new List<string>();
        foreach (var folder in Folders.Select(f => f.Folder).Distinct())
        {
            var directory = Path.Combine(themeDir, folder);
            if (!Directory.Exists(directory)) continue;
            foreach (var file in Directory.EnumerateFiles(directory, "*", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(themeDir, file).Replace('\\', '/');
                if (!outputs.ContainsKey(relative) && !relative.EndsWith(".import", StringComparison.Ordinal)) stale.Add(relative);
            }
        }
        stale.Sort(StringComparer.Ordinal);

        if (!options.Check)
            foreach (var (relative, bytes) in outputs)
            {
                var path = Path.Combine(themeDir, relative.Replace('/', Path.DirectorySeparatorChar));
                if (!Differs(path, bytes)) continue;
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllBytes(path, bytes);
            }

        // The checks: the content boot (asset keys through the chain) and the theme contract. With --check on a theme not yet written, only the mapping is known.
        var issues = new List<ValidationIssue>();
        var missing = new List<string>();
        var unused = new List<string>();
        if (File.Exists(AssetManifest.PathFor(options.ThemesDir, theme)))
        {
            var boot = ContentBoot.Check(options.ContentDir, theme);
            issues.AddRange(boot.Issues);
            if (boot.Database is { } database)
            {
                issues.AddRange(ThemeCheck.Check(database, options.ThemesDir, theme));
                var used = ThemeCheck.KeysContentUses(database);
                missing.AddRange(used.Where(k => !mapping.Assets.ContainsKey(k)).OrderBy(k => k, StringComparer.Ordinal));
                unused.AddRange(mapping.Assets.Keys.Where(k => !used.Contains(k) && k.StartsWith("model.", StringComparison.Ordinal) && !manifest.Any(e => e.Value?["anims"]?.GetValue<string>() == k))
                    .OrderBy(k => k, StringComparer.Ordinal));
            }
        }

        var result = new ImportResult { Theme = theme, Files = files, Variants = variants, Missing = missing, Unused = unused, Stale = stale, Issues = issues };
        return new ImportResult
        {
            Theme = theme, Files = files, Variants = variants, Missing = missing, Unused = unused, Stale = stale, Issues = issues,
            Report = Describe(result, pack, options.Check),
        };
    }

    private static void AddExtra(JsonObject entry, AssetMapping asset)
    {
        if (asset.Extra is null) return;
        foreach (var (name, value) in asset.Extra.OrderBy(e => e.Key, StringComparer.Ordinal))
            entry[name] = value switch
            {
                string s when bool.TryParse(s, out var b) => b,
                string s when double.TryParse(s, NumberStyles.Float, CultureInfo.InvariantCulture, out var d) => d,
                string s => s,
                _ => JsonNode.Parse(System.Text.Json.JsonSerializer.Serialize(value)),
            };
    }

    private static byte[] Model(string key, AssetMapping asset, string source, Mapping mapping, List<string> notes, string where)
    {
        GltfFile file;
        try
        {
            file = GltfFile.Load(source);
        }
        catch (Exception e) when (e is InvalidDataException or System.Text.Json.JsonException or FormatException)
        {
            throw new MappingException($"{where}: {e.Message}");
        }
        var rig = asset.Rig ?? asset.Skinned;
        if (rig is not null && mapping.Rigs.TryGetValue(rig, out var rigMap))
        {
            var renamed = GlbFixes.RenameBones(file, rigMap.Bones);
            if (renamed > 0) notes.Add($"{renamed} bone(s) renamed");
        }
        var isModel = key.StartsWith("model.", StringComparison.Ordinal);
        if (isModel && GlbFixes.NameMeshes(file, asset.Meshes?.Lod0, asset.Meshes?.Lod1, where) is { } meshes) notes.Add(meshes);
        if (GlbFixes.Armature(file) is { } armature) notes.Add(armature);
        if (GlbFixes.ScaleAndTurn(file, asset.Scale, GlbFixes.TurnFor(asset.Facing, where)) is { } fixedUp) notes.Add(fixedUp);
        if (isModel && asset.OutlineDirections && GlbFixes.OutlineDirections(file) is var outlined and > 0) notes.Add($"outline directions on {outlined} primitive(s)");
        return file.ToGlb();
    }

    private static bool Differs(string path, byte[] bytes) => !File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes);

    private static string Describe(ImportResult r, string pack, bool check)
    {
        var text = new StringBuilder();
        text.AppendLine($"themeimport: theme '{r.Theme}' from {pack}{(check ? " (check only: nothing written)" : "")}");
        foreach (var file in r.Files)
            text.AppendLine($"  {(file.Changed ? check ? "would write" : "wrote" : "unchanged"),-11} {file.Path}{(file.Notes.Count > 0 ? "  (" + string.Join("; ", file.Notes) + ")" : "")}");
        foreach (var key in r.Variants) text.AppendLine($"  variant     {key}");
        var written = r.Files.Count(f => f.Changed);
        text.AppendLine($"done: {r.Files.Count - 1} file(s) for {r.Files.Count - 1 + r.Variants.Count} key(s) ({r.Variants.Count} variant(s)); {written} {(check ? "would change" : "changed")}, {r.Files.Count - written} unchanged");

        if (r.Missing.Count > 0)
        {
            text.AppendLine($"missing: {r.Missing.Count} key(s) content uses are not in this theme; default's placeholders stand in:");
            foreach (var group in r.Missing.GroupBy(k => k[..(k.IndexOf('.', k.IndexOf('.') + 1) is var second and > 0 ? second : k.Length)]))
                text.AppendLine($"  {group.Key}: {string.Join(", ", group.Select(k => k[(group.Key.Length + 1 <= k.Length ? group.Key.Length + 1 : k.Length)..]))}");
        }
        else text.AppendLine("missing: none; every key content uses is in this theme");
        if (r.Unused.Count > 0) text.AppendLine($"not used by content: {string.Join(", ", r.Unused)} (fine for a variant base or later content; otherwise check the key)");
        if (r.Stale.Count > 0) text.AppendLine($"stale: {r.Stale.Count} file(s) in the theme that the mapping does not produce (delete them or map them): {string.Join(", ", r.Stale)}");

        var errors = r.Issues.Count(i => i.Severity == ValidationSeverity.Error);
        var warnings = r.Issues.Count - errors;
        if (r.Issues.Count == 0) text.AppendLine("rules: the theme meets the contract (docs/THEMES.md)");
        else
        {
            text.AppendLine($"rules: {errors} failure(s), {warnings} warning(s) (docs/THEMES.md says what each rule wants):");
            foreach (var issue in r.Issues.OrderByDescending(i => i.Severity).ThenBy(i => i.File, StringComparer.Ordinal).ThenBy(i => i.Line))
                text.AppendLine($"  {(issue.Severity == ValidationSeverity.Error ? "FAIL" : "warn")} {issue.Code}: {issue.Message}");
        }
        text.Append(errors == 0 ? "OK" : "FAILED");
        return text.ToString();
    }
}
